```
## Scope
<что анализируем, какой бизнес-процесс, какие данные>

## Применимые акты
| Акт | Применимость | Почему |

## Соответствие
| Требование | Норма | Статус | Что сделать |
|------------|-------|--------|-------------|
| Согласие на обработку ПД | ст. 9 ФЗ-152 | ✗ нет формы | Заверстать на лендинге |
| ...                      | ...           | ✓      | -           |

## Риски
- <риск> | <санкция> | <вероятность> | <митигация>

## Дорожная карта
1. <шаг>  (срок, ответственный)
2. ...
```

## Когда сомневаешься
