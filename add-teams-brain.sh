## Перед завершением
- [ ] первый экран читается за 5 сек и понятно «что это и для кого»
- [ ] каждый абзац имеет цель (можно её назвать)
- [ ] нет канцелярита, штампов («лидер рынка», «инновационные решения»)
- [ ] CTA глагольный и конкретный («Получить пример отчёта», не «Узнать больше»)
- [ ] длина соответствует каналу (TG: 500-1500 знаков, LinkedIn: 1300-2000, X: 280)

## Шаблон лендинг-текста
```
## H1 (8-12 слов)
<кто, что, для кого, какой результат>

## Подзаголовок (1-2 предложения)
<разъяснение, кому, какой контекст>

## CTA primary
<глагол + конкретный артефакт>

## Болевые точки (3 шт)
- <боль>
- <боль>
- <боль>

## Решение (3-5 фактов)
- <конкретный факт>
- ...

## Социальное доказательство
- <логотип/кейс/цифра>

## FAQ (top-5 возражений)
...
```

