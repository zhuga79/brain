"""Общая точка входа для CLI-обёрток Python: гасит BrokenPipeError на stdout.

Пользователь обычного шелла (не только тесты) нередко обрывает чтение
раньше конца вывода: `brain-doctrine list | grep -q ...`, `| head`,
интерактивный `less`, нажатый `q`. Продюсер получает EPIPE на следующей
записи; необработанный `BrokenPipeError` валит процесс с ненулевым кодом и
трейсбеком в полностью корректном сценарии использования — читатель получил
всё, что искал, это не ошибка продюсера.

Это НЕ замена защите в тестах: там конструкция `продюсер | grep -q`
устранена целиком (см. tests/_lib.sh:capture_output — продюсер запускается
внутри `$(...)`, живого читателя, способного оборвать запись, там просто
нет). Здесь гасится тот же класс ошибки для интерактивного и скриптового
использования CLI за пределами тестов, откуда пайп не выкинуть — это
законный способ пользоваться `brain-status`, `brain-doctrine` и т.п.

Раньше try/except BrokenPipeError был скопирован в `brain-status` отдельно
(t-2026-08-16, до этого тикета). Здесь он вынесен в общее место, чтобы
остальные семь продюсеров с тем же паттерном (`| grep -q` на их выводе)
не копировали идентичный блок каждый в своём файле — правка гарантии
или формулировки сообщения делается один раз.
"""

from __future__ import annotations

import os
import sys
from typing import Callable, Optional


def run_cli(main: Callable[[], Optional[int]]) -> None:
    """Вызвать main() как точку входа CLI, погасив BrokenPipeError.

    Ожидается вызов из `if __name__ == "__main__": run_cli(main)`.
    main() может вернуть код выхода (int) или сам завершить процесс через
    sys.exit()/raise SystemExit — оба стиля используются в разных Brain CLI.
    """
    try:
        result = main()
    except BrokenPipeError:
        # Документированный приём (см. Note в man-странице signal(7) и
        # примере в документации Python по SIGPIPE): нужно перенаправить
        # stdout в /dev/null ПЕРЕД выходом. Иначе при завершении интерпретатор
        # попробует дофлашить буфер stdout и получит то же исключение ещё
        # раз — уже неперехваченным, с трейсбеком на stderr и неверным кодом
        # возврата, хотя мы только что его погасили.
        devnull = os.open(os.devnull, os.O_WRONLY)
        os.dup2(devnull, sys.stdout.fileno())
        raise SystemExit(0)
    if result is not None:
        raise SystemExit(result)
