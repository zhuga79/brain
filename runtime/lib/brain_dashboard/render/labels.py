"""Как состояние задачи называется и красится на странице.

Это решения оформления, а не данные: сбор отдаёт состояние символом грамматики
(` `, `~`, `x`, `!`), а как назвать его человеку и каким классом покрасить —
дело слоя рендеринга. Пока константы жили в модуле сбора, слои были связаны
в обратную сторону: чтобы поменять подпись, приходилось править сборщик.
"""

from __future__ import annotations

STATE_LABELS = {" ": "open", "~": "in_progress", "x": "done", "!": "blocked"}
STATE_CLASS = {" ": "state-open", "~": "state-progress", "x": "state-done", "!": "state-blocked"}
