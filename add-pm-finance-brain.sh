## Календарь налоговых сроков (РФ, типичные)
- УСН авансы: 28 апреля / 28 июля / 28 октября
- УСН годовой (ИП): 28 апреля следующего года
- УСН годовой (ООО): 28 марта следующего года
- НДФЛ агентский: до 28 числа след. месяца (ЕНС)
- Страховые ИП: фикс до 31 декабря, 1% свыше 300k — до 1 июля
- НДС: 28 апреля / июля / октября / января (трети суммы)
- 6-НДФЛ: до 25 числа после квартала

