# Универсальная функция: удалить старый блок «Зоны на стыке» (если есть) и
# дописать новый. Это делает скрипт идемпотентным и обновляет блок к новой версии.
replace_boundary_block() {
  local file="$1"
  local new_block="$2"
  python3 - "$file" "$new_block" <<'PY'
import sys, pathlib, re
p = pathlib.Path(sys.argv[1])
new = sys.argv[2]
txt = p.read_text()
# вырезать существующий блок "## Зоны на стыке" до конца файла или до
# следующего "## " того же уровня
pat = re.compile(r"\n## Зоны на стыке.*?(?=\n## |\Z)", re.S)
if pat.search(txt):
    txt = pat.sub("", txt)
txt = txt.rstrip() + "\n\n" + new + "\n"
p.write_text(txt)
PY
}

