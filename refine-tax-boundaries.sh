## Эскалация — flowchart

```
Вопрос про налоги?
   │
   ├─ Просто посчитать? → tax-advisor (один)
   │
   ├─ Учёт операции? → accountant (один)
   │
   ├─ Договор/форма влияет на налог? → council [tax-advisor, lawyer]
   │
   ├─ ФНС требует/проверяет? → tax-advisor primary, lawyer консультирует;
   │                            при споре в суде — lawyer primary
   │
   ├─ Регуляторный процесс (отчётность валютная, AML, КИК)?
   │     → compliance + tax-advisor (council)
   │
   └─ Уголовные риски? → lawyer (адвокат) primary, tax-advisor — эксперт
```

