## Запреты (что роли НЕ должны делать в налоговой зоне)

- **lawyer** не считает налог. Может сказать «возникает НДФЛ», но не сумму.
  Сумма — у tax-advisor.
- **compliance** не выбирает режим и не считает налог. Может проверить
  процесс должной осмотрительности.
- **accountant** не интерпретирует норму НК. Проводит то, что задано режимом.
- **tax-advisor** не пишет договор и не идёт в суд. Готовит требования к
  договору и материал для процессуального юриста.

