## Маппинг типовых вопросов → к кому идти

| Вопрос | Primary | Совет нужен? |
|--------|---------|--------------|
| «Сколько я заплачу налогов в этом году по УСН-6?» | tax-advisor | нет, если accountant дал доход |
| «Как провести возврат от клиента в учёте?» | accountant | возможно tax-advisor (НДС-влияние) |
| «Можно ли сделать договор с самозанятым?» | tax-advisor + lawyer | да, council |
| «ФНС прислала требование пояснить расхождение в декларации» | tax-advisor | если решение оспаривать → +lawyer |
| «Платим ли мы НДС с зарубежного клиента?» | tax-advisor | возможно compliance (валютный контроль) |
| «Можем ли применить ИТ-льготу?» | tax-advisor | да, council с lawyer и compliance |
| «Как оформить грант для АНО?» | accountant + tax-advisor (целевые поступления, ст. 251 НК) | да, council с lawyer |
| «Нужна ли политика обработки ПД?» | compliance | если в договорах есть PD-условия — +lawyer |
| «У нас 3 ИП, ФНС подозревает дробление» | tax-advisor + lawyer | да, council, срочно |
| «Какой ОКВЭД ставить?» | tax-advisor (с т.зр. режима/льгот) + compliance (с т.зр. лицензирования) | возможно |

