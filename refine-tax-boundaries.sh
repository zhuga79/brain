Документ снимает вечный конфликт «кто отвечает за налоговую часть».
Все агенты обязаны читать его при работе с налоговыми вопросами.

## Принцип: налоговый цикл состоит из 4 этапов

```
   ┌─────────────┐    ┌─────────────┐    ┌──────────────────┐    ┌─────────────┐
   │  1. УЧЁТ    │ →  │  2. РАСЧЁТ  │ →  │ 3. СТРУКТУРА     │ →  │ 4. ЗАЩИТА   │
   │ что было    │    │ сколько НК  │    │ как сделать      │    │ если ФНС    │
   │ accountant  │    │ tax-advisor │    │ tax-advisor +    │    │ tax-advisor │
   │             │    │             │    │ lawyer           │    │ + lawyer    │
   └─────────────┘    └─────────────┘    └──────────────────┘    └─────────────┘
```

У каждого этапа свой primary. Это снимает 90% споров «к кому идти».

---

## Этап 1. УЧЁТ — primary: `accountant`

**Зеркало операции.** Что произошло, как оформляется первичкой,
как попадает в ОСВ, КУДиР, декларацию.

### Что accountant делает в налоговом контексте
- Заводит первичку: акты, УПД, чеки самозанятых, инвойсы.
- Разносит операции по счетам / ОКВЭДам / категориям расходов.
- Готовит исходные данные для расчёта налога (книга учёта доходов и расходов).
- Сверяет с ЕНС: что начислено, что уплачено, что осталось.
- Готовит документы к декларациям: реестры, ведомости.

### Чего accountant НЕ делает в налогах
- Не выбирает режим налогообложения.
- Не считает «налог-к-уплате» как стратегическое решение (только техническая
  калькуляция по правилам, которые задал tax-advisor).
- Не отвечает на вопросы ФНС по существу.
- Не обосновывает применение льгот / пониженных ставок.

---

## Этап 2. РАСЧЁТ — primary: `tax-advisor`

**Сколько в бюджет.** Какой режим, какая ставка, какие льготы, какие сроки,
сколько конкретно платить.

### Что tax-advisor делает
- Выбор режима: НПД / ПСН / УСН-6 / УСН-15 / ОСНО / АУСН — расчётом, не на глаз.
- Расчёт налогов: УСН, НДФЛ, страховые, НДС, имущественные.
- Льготы: ИТ-льгота, региональные пониженные ставки УСН, патент по виду.
- Календарь: что когда платить, какие отчёты сдавать.
- Налогообложение спецактивов: крипта (ст. 220 НК), ценные бумаги,
  иностранные дивиденды, НКО (ст. 251 НК).
- Валютный контроль (НК-сторона): отчётность по зарубежным счетам,
  поступления от нерезидентов, КИК (ст. 25.13-25.15 НК).

### Чего tax-advisor НЕ делает
- Не ведёт учёт.
- Не пишет договор (только указывает требования к нему — какие условия
  обеспечат нужную налоговую квалификацию).
- Не идёт в суд (это процессуальная часть → lawyer).
- Не выстраивает регуляторный процесс должной осмотрительности
  (это compliance, см. этап 3).

---

## Этап 3. СТРУКТУРИРОВАНИЕ — primary: `tax-advisor`, обязательный совет с `lawyer`

**Как сделать, чтобы законно платить меньше.** Любой выбор формы /
договорной конструкции / контрагента имеет налоговые последствия.

### Зона раздела
- **tax-advisor**: какие налоговые последствия у каждого варианта.
- **lawyer**: какие правовые последствия и риски квалификации.
- **compliance**: проверка регуляторных рисков (ст. 54.1 НК — должная
  осмотрительность; 115-ФЗ; контролируемые сделки).

### Типовые ситуации, требующие совета `[tax-advisor, lawyer]` (минимум):

| Ситуация | Что решают |
|----------|-----------|
| Выбор формы (ИП / ООО / АНО / самозанятый) | tax: налог; lawyer: ответственность, форма работы |
| Договор: услуги vs подряд vs заказ ПО (ст. 779 / 702 / 1296 ГК) | tax: НДС, прибыль; lawyer: правовая природа |
| Самозанятый-контрагент | lawyer: чтобы не переквалифицировали в трудовой (ст. 19.1 ТК); tax: лимит 2.4 млн, риск признания работодателем |
| Дробление бизнеса | tax: легальность с т.зр. НК (ст. 54.1); lawyer: правомерность структуры |
| Зарубежный клиент / счёт | tax: 173-ФЗ + НК; lawyer: договорная сторона + валютная оговорка |
| Привлечение инвестиций | tax: налоговые последствия типа сделки (займ vs доля); lawyer: корпоративные процедуры |
| ИТ-льгота (пониженный налог + взносы) | tax: расчёт выгоды; lawyer: документы, ОКВЭД, аккредитация Минцифры |

### Когда подключается `compliance`
- 115-ФЗ AML: проверка контрагента, источник средств.
- Ст. 54.1 НК: должная осмотрительность как **процесс** (не разовая проверка
  в моменте, а регулярный мониторинг).
- Контролируемые сделки (ст. 105.14 НК) и трансфертное ценообразование.
- Если структура задевает 152-ФЗ / 187-ФЗ / 259-ФЗ — compliance primary
  по этим зонам, tax-advisor смотрит налоговую сторону.

---

## Этап 4. ЗАЩИТА — двойной primary: `tax-advisor` (существо) + `lawyer` (процесс)

**ФНС пришла.** Камеральная проверка, выездная, требование пояснений,
акт, решение, апелляция, суд.

### Разделение
| Подэтап | Primary | Что делает |
|---------|---------|-----------|
| Требование/запрос пояснений | tax-advisor | Готовит ответ по существу: расчёт, документы, обоснование |
| Возражения на акт проверки | tax-advisor + lawyer | tax: существо налога; lawyer: процессуальные нарушения, формальности |
| Апелляция в УФНС | lawyer (primary) + tax-advisor | Жалоба как процессуальный документ |
| Судебное обжалование | lawyer (primary) + tax-advisor | tax-advisor — эксперт по существу, lawyer — процесс |
| Уголовные риски (ст. 198, 199 УК — уклонение) | lawyer (primary, желательно адвокат) | Налоговая + уголовная защита |

### Compliance в защите
Только если в ходе проверки выявлены регуляторные нарушения (PD, AML,
валютный контроль), которые ФНС использует как доп.основания —
тогда compliance подключается параллельно.

---

## Серые зоны (всегда council)

Эти ситуации **обязательно** идут через `mode: council` со списком ролей:

| Ситуация | Роли |
|----------|------|
| Налоговая проверка с риском уголовного состава | `[tax-advisor, lawyer, compliance]` |
| Структурирование международной сделки | `[tax-advisor, lawyer, compliance, cfo]` |
| Спор с контрагентом о налоговой переквалификации | `[tax-advisor, lawyer, accountant]` |
| Запуск нового продукта с налоговыми льготами | `[tax-advisor, compliance, lawyer, cfo]` |
| Выбор формы при наличии нескольких видов деятельности | `[tax-advisor, lawyer, cfo]` |
| Изменение режима с одного на другой | `[tax-advisor, accountant, cfo]` |

