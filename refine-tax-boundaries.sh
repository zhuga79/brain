# Legal vs Compliance — общее разграничение

`lawyer` и `compliance` часто конфликтуют. Простое правило снимает спор:

## Правило

- **lawyer** = что ЗАПИСАНО (в договоре, уставе, доверенности, судебном акте)
- **compliance** = что ТРЕБУЕТСЯ КАК ПРОЦЕСС (регулярная отчётность, политики,
  процедуры, обязательные действия)

## Тест на различение

Спроси: «Это разовый документ или регулярный процесс?»

- Разовый документ (договор / устав / претензия / иск) → **lawyer**
- Регулярный процесс (политика, отчётность, мониторинг) → **compliance**

## Пограничные случаи

| Ситуация | Primary | Почему |
|----------|---------|--------|
| Согласие на обработку ПД (один документ) | lawyer | разовая форма |
| Политика обработки ПД (постоянная для сайта) | compliance | регулярный процесс |
| Подача уведомления оператора в РКН | compliance | процессуальное действие регулярного характера |
| Договор обработки ПД с подрядчиком | lawyer | разовый документ |
| Реакция на запрос субъекта ПД (раз в N) | compliance | регулярный процесс ответов |
| Иск от субъекта ПД в суд | lawyer | разовая правовая ситуация |
| Реестр персональных данных (актуализация) | compliance | мониторинг |
| Ответ ФАС на жалобу о рекламе | lawyer | разовый документ |
| Соответствие маркировки рекламы 38-ФЗ как процесс | compliance | регулярный процесс |
| Договор о неразглашении (NDA) | lawyer | разовый документ |
| Программа защиты коммерческой тайны (приказы, доступы, гриф) | compliance | регулярный процесс |

## Когда нужны оба

Если требуется и **зашить требование в договор**, и **запустить процесс
исполнения** — это council `[lawyer, compliance]`.

Пример: переход на работу с зарубежным заказчиком.
- lawyer: договор с валютной оговоркой, applicable law, юрисдикция.
- compliance: процесс валютного контроля с банком (паспорта сделок,
  отчётность, сроки репатриации).
- tax-advisor: налоговая сторона (см. tax-boundaries.md).
